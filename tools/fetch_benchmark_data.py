"""Fetch a pinned subset of real ORCA output for parser validation.

Third-party data is **never vendored into this repository**. This script downloads a small,
fixed set of log files from ``cclib-data`` into an ignored directory, and checks them against
``tools/benchmark_manifest.json`` so a run is reproducible.

Usage::

    python tools/fetch_benchmark_data.py              # download and verify
    python tools/fetch_benchmark_data.py --verify     # re-check what is already present
    python tools/fetch_benchmark_data.py --update-manifest   # re-pin after a deliberate bump

Licence: ``cclib`` itself is BSD-3-Clause; the data repository must be checked before any
file is redistributed. Because nothing is redistributed here, only the licence of this script
-- the project's own -- applies. See ``docs/benchmarks.md``.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import urllib.error
import urllib.request
from pathlib import Path

REPOSITORY = "cclib/cclib-data"
MANIFEST_PATH = Path(__file__).with_name("benchmark_manifest.json")
DEFAULT_DEST = Path(".benchmark-data")
TIMEOUT_SECONDS = 60

# Chosen to span ORCA 2.6 through 5.0 and to include the awkward cases: an unconverged
# optimisation, a job that reached its cycle limit, a very long input echo, and a
# spin-orbit calculation.
ORCA_FILES: tuple[str, ...] = (
    "ORCA/ORCA2.6/dvb_sp.out",
    "ORCA/ORCA2.9/dvb_td.out",
    "ORCA/ORCA3.0/dvb_ir.out",
    "ORCA/ORCA3.0/dvb_gopt_unconverged.out",
    "ORCA/ORCA4.0/dvb_td.out",
    "ORCA/ORCA4.1/dvb_gopt.out",
    "ORCA/ORCA4.2/dvb_sp.out",
    "ORCA/ORCA4.2/dvb_ir.out",
    "ORCA/ORCA4.2/dvb_td.out",
    "ORCA/ORCA4.2/long-input.out",
    "ORCA/ORCA5.0/1177.out",
    "ORCA/ORCA5.0/dvb_soc.log",
)


def _raw_url(commit: str, path: str) -> str:
    return f"https://raw.githubusercontent.com/{REPOSITORY}/{commit}/{path}"


def _digest(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _download(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=TIMEOUT_SECONDS) as response:
        payload: bytes = response.read()
    return payload


def _fetch_one(dest_root: Path, commit: str, path: str, expected_digest: str) -> str:
    """Download one file, checksum it, and only then let it reach the disk.

    The digest is checked against the in-memory payload *before* anything is written, so a
    mismatch cannot leave a corrupt file behind for the next run to trust.
    """
    target = dest_root / path
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        payload = target.read_bytes()
    else:
        try:
            payload = _download(_raw_url(commit, path))
        except (urllib.error.URLError, TimeoutError, OSError) as error:
            return f"MISSING {path}: {error}"
        digest = _digest(payload)
        if digest != expected_digest:
            return f"MISMATCH {path}: expected {expected_digest}, got {digest}"
        target.write_bytes(payload)
        return f"ok {path} ({len(payload)} bytes, {digest[:12]})"
    digest = _digest(payload)
    if digest != expected_digest:
        return f"MISMATCH {path}: expected {expected_digest}, got {digest}"
    return f"ok {path} ({len(payload)} bytes, {digest[:12]})"


def _load_manifest() -> dict[str, object]:
    if not MANIFEST_PATH.exists():
        return {"repository": REPOSITORY, "commit": None, "files": {}}
    loaded: object = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    if not isinstance(loaded, dict):
        return {"repository": REPOSITORY, "commit": None, "files": {}}
    return {str(key): value for key, value in loaded.items()}


def _load_entries() -> tuple[str | None, dict[str, str]]:
    """The pinned commit and each file's recorded checksum, typed once.

    A malformed manifest is refused rather than half-read, because a partial pin would let
    some files be reported as verified when nothing actually checked them.
    """
    manifest = _load_manifest()
    commit = manifest.get("commit")
    raw_files = manifest.get("files")
    entries: dict[str, str] = {}
    if isinstance(raw_files, dict):
        for name, value in raw_files.items():
            digest = value.get("sha256") if isinstance(value, dict) else None
            if isinstance(name, str) and isinstance(digest, str):
                entries[name] = digest
    return (commit if isinstance(commit, str) and commit else None), entries


def _write_manifest(commit: str, files: dict[str, dict[str, object]]) -> None:
    MANIFEST_PATH.write_text(
        json.dumps(
            {
                "repository": REPOSITORY,
                "commit": commit,
                "note": (
                    "Generated by tools/fetch_benchmark_data.py. Contains no data, only the "
                    "pin and the checksums needed to verify a fetch."
                ),
                "files": dict(sorted(files.items())),
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )


def _resolve_commit() -> str:
    manifest = _load_manifest()
    commit = manifest.get("commit")
    if isinstance(commit, str) and commit:
        return commit
    request = urllib.request.Request(
        f"https://api.github.com/repos/{REPOSITORY}/commits?per_page=1",
        headers={"Accept": "application/vnd.github+json", "User-Agent": "qcjudge-fetch"},
    )
    with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
        payload = json.loads(response.read().decode("utf-8"))
    return str(payload[0]["sha"])


def _manifest_problems(recorded: dict[str, str]) -> list[str]:
    """Why this manifest cannot verify the files it is supposed to pin.

    A file with no recorded checksum cannot be verified, and describing it as verified would
    defeat the point of the pin. The key sets must match in both directions: a file the
    manifest does not describe is unverifiable, and an entry describing no file is a pin that
    is never checked.
    """
    recorded_keys = set(recorded)
    wanted_keys = set(ORCA_FILES)
    problems: list[str] = []
    undescribed = sorted(wanted_keys - recorded_keys)
    stale = sorted(recorded_keys - wanted_keys)
    if undescribed:
        problems.append(
            f"the manifest records no checksum for {len(undescribed)} file(s), so they cannot "
            f"be verified: {undescribed}"
        )
    if stale:
        problems.append(
            f"the manifest records checksums for {len(stale)} file(s) that are no longer "
            f"fetched, so those pins are never checked: {stale}"
        )
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dest", type=Path, default=DEFAULT_DEST)
    parser.add_argument(
        "--verify",
        action="store_true",
        help="check the files already present instead of downloading anything new",
    )
    parser.add_argument(
        "--update-manifest",
        action="store_true",
        help="re-pin the commit and record the checksums of the fetched files",
    )
    args = parser.parse_args(argv)

    pinned, recorded = _load_entries()

    problems = _manifest_problems(recorded)
    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        print(
            "refusing to report these files as verified; run --update-manifest to re-pin "
            "deliberately",
            file=sys.stderr,
        )
        return 2

    if pinned is not None:
        # A pinned commit is authoritative: re-resolving it would silently float the pin.
        commit = pinned
    else:
        try:
            commit = _resolve_commit()
        except (urllib.error.URLError, TimeoutError, OSError) as error:
            print(f"cannot reach {REPOSITORY}: {error}", file=sys.stderr)
            return 2
    if not commit:
        print("no commit is pinned and none could be resolved", file=sys.stderr)
        return 2

    if args.verify:
        missing = [
            path for path in ORCA_FILES if not (args.dest / path).exists()
        ]
        if missing:
            print(
                f"{len(missing)} of {len(ORCA_FILES)} files are not present under "
                f"{args.dest}; run without --verify to fetch them.",
                file=sys.stderr,
            )
            return 1

    new_files: dict[str, dict[str, object]] = {}
    failures = 0
    for path in ORCA_FILES:
        if args.verify:
            payload = (args.dest / path).read_bytes()
            digest = _digest(payload)
            expected = recorded[path]
            if digest != expected:
                print(
                    f"MISMATCH {path}: manifest records {expected}, file is {digest}",
                    file=sys.stderr,
                )
                failures += 1
            else:
                print(f"ok {path} ({digest[:12]})")
            new_files[path] = {"sha256": digest, "bytes": len(payload)}
            continue
        status = _fetch_one(args.dest, commit, path, recorded[path])
        print(status)
        if status.startswith("MISMATCH") or status.startswith("MISSING"):
            failures += 1
            continue
        payload = (args.dest / path).read_bytes()
        new_files[path] = {"sha256": _digest(payload), "bytes": len(payload)}

    if args.update_manifest:
        if failures:
            print(
                f"refusing to write a manifest while {failures} file(s) failed, because it "
                "would pin data that could not be verified",
                file=sys.stderr,
            )
            return 1
        _write_manifest(commit, new_files)
        print(f"manifest written: {MANIFEST_PATH} (commit {commit[:12]})")

    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
